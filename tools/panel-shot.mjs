import { chromium } from 'playwright';
import fs from 'node:fs';
const save = fs.readFileSync(process.argv[2], 'utf8');
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('file://' + process.cwd() + '/dist/creekfolk.html');
await page.waitForFunction(() => window.__creek && window.__creek.world, null, { timeout: 30000 });
await page.evaluate(async (s) => { const w = JSON.parse(s); w.realStart = Date.now() - w.t * 1000; w.skip = 0; window.__creek.frame = () => {}; window.__creek.world = null; await window.__creek.store.put('main', JSON.stringify(w)); }, save);
await page.reload();
await page.waitForFunction(() => window.__creek && window.__creek.world, null, { timeout: 60000 });
await page.evaluate(() => document.querySelectorAll('[data-go], .summary button').forEach((b) => b.click()));
await page.waitForTimeout(1500);
const id = await page.evaluate(() => __creek.world.creatures.find((c) => c.stage === 'adult' && !c.visitor).id);
await page.evaluate((id) => __creek.select(id), id);
await page.waitForTimeout(1500);
await page.screenshot({ path: process.argv[3] });
console.log(await page.evaluate(() => (document.querySelector('.sheet') || document.body).innerText.slice(0, 400)));
console.log(logs.join('\n') || '(no errors)');
await browser.close();
